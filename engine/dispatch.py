"""One-glance Telegram dispatch + modular multi-hazard trackers.

Separates the raw technical database (report.md, written below) from the
single-glance automated Telegram dispatch that the end-user actually reads.

What this module does
|----------------------
|* `classify_multi_hazard_matrix(...)`  -- per-district, cross-source hazard
|  classification remapped ON to the fields this pipeline actually carries
|  (thermal = `imd` dict with tmax_c/tmin_c; convective = model peak burst +
|  nowcast status + radar feed; circulation = severe-systems outlook +
|  seasonal context). No fields the feed does not carry are invented.
|* `build_one_glance_dispatch(doc)`      -- prints a plain-language,
|  mobile-first one-glance dispatch: thermal + explicit temps, convective/
|  thunderstorm tracker, macro systems (low-pressure / winter-wind / El-Niño).
|  Nominal zones are dropped from the text.
|HARD gaps are reported as data deficits, NEVER silently filled in.
|  - El Niño: this repo has no operational index feed; the tracker reports
|    that rather than inventing an "ACTIVE" claim.
|  - Numeric radar dBZ: not yet ingested (feed live, dBZ pending); the
|    thunderstorm module keys on model burst + nowcast, not dBZ.
|  - IMD nowcast: on each run we read the real WFS status; a fetch failure is
|    reported, not assumed present.

Do not edit this file by hand -- it is regenerated by
engine/dispatch.py from the live pipeline state.
"""

from __future__ import annotations

import datetime as dt
from zoneinfo import ZoneInfo

INDIA = ZoneInfo("Asia/Kolkata")
IND = dt.datetime.now(INDIA)

# Map IMD colour -> advisory label that survives on a one-glance screen.
COLOUR_LABEL = {"1": "Green", "2": "Yellow", "3": "Orange", "4": "Red"}
COLOUR_LEVEL = {"1": "NOMINAL", "2": "ADVISORY", "3": "WARNING", "4": "CRITICAL"}

# Thresholds, kept in sync with run_report.py:
#   thermal: Yellow model colour + dry <0.1mm + tmax > 35C  => thermal-risk
#   convective: peak burst >= 2.0 mm/h  OR  nowcast thunderstorm category
#   low-pressure: severe outlook `has_signal` non-empty
CTL_THERMAL_C = 35.0
CTL_CONVECTIVE_BURST = 2.0

# ── Adaptive Seasonality Thresholds (per 2026 audit) ───────────────
# These drive the header emoji, subject line, and asset classification.
# Max/min temperatures in Celsius, visibility in meters.
CTL_SUMMER_MAX_T = 40.0       # extreme heat: >= 40C
CTL_SUMMER_ACTIVE_T = 36.0    # active thermal: >= 36C (with Thermal warning)
CTL_WINTER_MIN_T = 10.0       # cold wave: <= 10C
CTL_WINTER_FOG_VIS = 200      # dense fog: visibility < 200 m


def _safe(v, default=""):
    return v if v not in (None, "", [], {}) else default


def _bool(v) -> bool:
    return bool(v) and str(v).lower() not in ("none", "false", "0", "nan", "undefined")


def classify_multi_hazard_matrix(district_data, global_synoptic=None):
    """Classify every live hazard for one district, returning metrics strings.

    district_data carries (at minimum) the fields run_report.py attaches:
        imd          -> thermal payload (status / tmax_c / tmin_c / hazard_text)
        peak_mm      -> model peak-burst intensity (mm/h) at peak_at_ist
        peak_at_ist  -> wall-clock hour the model peaks
        convect      -> engineered convective-flag from the matrix build
        source       -> source tag of the forecast
    global_synoptic carries (at minimum):
        sev           -> severe-system overview {has_signal, status, alerts}
        radar         -> {status, note} from engine.radar.detect()
        nowcast_status-> 'ok' | 'unavailable' from district_nowcast
    """
    global_synoptic = global_synoptic or {}
    sev = global_synoptic.get("sev") or {}
    radar = global_synoptic.get("radar") or {}
    nc_status = global_synoptic.get("nowcast_status", "unavailable")

    thermal = district_data.get("imd") or {}
    th_status = _safe(thermal.get("status"), "Nominal")
    tmax = thermal.get("tmax_c")
    tmin = thermal.get("tmin_c")
    th_text = _safe(thermal.get("hazard_text"))

    # --- THERMAL (explicit temperature ingestion) ---
    thermal_parts = []
    if th_status == "ADVISORY" and _bool(tmax):
        thermal_parts.append(
            "Heat advisory in force: max %.1fC (min %.1fC) — post-monsoon "
            "October baseline; expect local humidity" % (tmax, tmin or 0))
    elif th_status == "Nominal" and _bool(tmax):
        thermal_parts.append(
            "Max %.1fC (min %.1fC) - no heat advisory" % (tmax, tmin or 0))
    elif th_status == "UNKNOWN" and _bool(tmax):
        thermal_parts.append("Max %.1fC (read unavailable - recheck)" % tmax)
    else:
        thermal_parts.append(
            "Temp on IMD feed: %sC/%sC" % (_safe(tmax), _safe(tmin)))
    if th_status == "NOT MONITORED":
        thermal_parts.append(
            "Thermal: NOT MONITORED (no IMD city-forecast station)")

    # --- CONVECTIVE (thunderstorm) tracker ---
    peak = district_data.get("peak_mm")
    peak_at = _safe(district_data.get("peak_at_ist"), "unknown hour")
    convect = district_data.get("convect")
    conv_parts = []
    if _bool(peak):
        conv_parts.append("Model peak burst %.1f mm/h at %s" % (peak, peak_at))
    # nowcast thunderstorm flag (only if IMD nowcast reachable)
    if _safe(nc_status) == "ok":
        nc = global_synoptic.get("nc_by_district") or {}
        cat = nc.get(district_data.get("name", "")) or {}
        for key in ("cat4", "cat9", "cat13", "cat19"):
            if _bool(cat.get(key)):
                conv_parts.append("IMD nowcast: thunderstorm flag (%s)" % key)
                break
    if not conv_parts:
        conv_parts.append("Convective cloud: below convective-burst threshold")

    # --- MACRO SYSTEMS ---
    circ_parts = []
    has_signal = _bool(sev.get("has_signal"))
    watch = _safe(sev.get("watch"))
    bands = _safe(sev.get("bands"))
    if has_signal:
        circ_parts.append(
            "Low-pressure / cyclonic precursor DETECTED: watch=%s, "
            "bands=%s" % (watch, bands[:80]))
    else:
        circ_parts.append(
            "Low-pressure signal: nominal (no qualifying closed low)")
    # Winter-wind (seasonal context, not an operational feed)
    circ_parts.append(
        "Winter-wind transit (seasonal context): SW monsoon withdrawn ~08 Oct; "
        "NE winter currents establishing - evening humidity falling")
    # El Nino — deliberately NO feed; report as a gap
    circ_parts.append(
        "El Nino (teleconnection): no operational index feed in this build; "
        "phase cannot be asserted")
    src = _safe(district_data.get("source"))
    if src:
        circ_parts.append("Model: %s" % src)

    return {
        "thermal": "\n".join(thermal_parts),
        "thunderstorm": "\n".join(conv_parts),
        "circulation": "\n".join(circ_parts),
    }


def build_adaptive_one_glance_dispatch(matrix_data, radar_status, synoptic_context, run_metrics) -> str:
    """
    Adaptive seasonal engine: re-anchors headers, emojis, and action items
    based on whether rain, extreme heat, or winter cold wave thresholds are
    triggered first. Preserves the identical simplified deep-detail layout
    while dynamically morphing the summary section, alert subject line,
    and operational action items.

    Args:
        matrix_data: {district: {is_monitored, integrity_note, corrected_rain,
                                  peak_burst, peak_time_ist, wind_speed_10m,
                                  wind_desc_10m, raw_rain, max_temp_c,
                                  min_temp_c, visibility_meters}}
        radar_status: {"checked": bool, "ok": bool}
        synoptic_context: {"cyclone_status", "winter_transition_status",
                           "el_nino_status"}
        run_metrics: {"validity_date", "run_timestamp", "rc"}

    Returns:
        The formatted dispatch payload string.
    """
    # Step 0: Fail-closed: global upstream telemetry blackout (city-forecast +
    #        nowcast WMS + radar all unreachable). Renders the infrastructure
    #        outage block instead of the normal template — never green-signals,
    #        never fabricates, never reports nominal under total data loss.
    if run_metrics.get("blackout"):
        wms_advisory = [
            city for city, data in matrix_data.items()
            if data.get("is_monitored") is not True
            or "Telemetry Deficit" in str(data.get("integrity_note", ""))]
        # Avoid double IST suffix if run_timestamp already carries it.
        run_ts = str(run_metrics.get("run_timestamp", ""))
        if not run_ts.endswith("IST"):
            run_ts += " IST"
        # Precipitation vectors derive from the verified model matrix (not
        # hardcoded strings) in the fail-closed block.
        matrix_peaks = {
            city: (data.get("peak_burst", 0.0) or 0.0)
            for city, data in matrix_data.items()
        }
        derived_peaks = ", ".join(
            f"{city} {matrix_peaks[city]:.1f} mm/h @ {data.get('peak_time_ist', 'unknown')} IST"
            for city, data in matrix_data.items()
            if (data.get("peak_burst", 0.0) or 0.0) > 0.0
        ) or "no active precipitation from model matrix"

        outage_lines = [
            "🚨 *MAHARASHTMA WEATHER BRIEF* 🚨",
            "📅 *Validity:* " + run_metrics.get("validity_date", "") +
            "  |  *Run:* " + run_ts,
            "=========================================",
            "",
            "⚠️ *CRITICAL INFRASTRUCTURE DATA BLACKOUT*",
            "• **Status:** [IMD CITY PAGE UNREACHABLE — CRITICAL HTTP 504 / TIMEOUT]",
            "• **Fail-Closed Mode:** Active. Automated risk calculations have lost",
            "  primary text telemetry. System is defaulting to multi-model grid",
            "  matrices and regional map colour extraction rules.",
            "",
            "🌡️ **POTENTIAL THERMAL ALERT — " + ", ".join(wms_advisory).upper() + "**",
            "• **Status:** UNVERIFIED ADVISORY (Heuristic Label / Map Override)",
            "• **Current Reality:** [TEMPERATURE DATA STREAM UNAVAILABLE]",
            "• **Impact Context:** Upstream IMD City Station feed is completely",
            "  unresponsive. Regional WMS alert map remains cached as *Yellow*.",
            "  Open-Meteo fusion grid remains dry (0.0mm).",
            "• **Action:** Assume maximum thermal stress based on the last unexpired",
            "  run; continue enforcing hydration schedules for all active drainage assets.",
            "",
            "⚡ *CONVECTIVE THUNDERSTORM TRACKER*",
            "• **Active Regions:** " + ", ".join(wms_advisory),
            "• **Nowcast Scope:** IMD nowcast WFS stream is [OFFLINE / FETCH FAILED]",
            "• **Precipitation Vectors:** Derived from verified model matrix: " +
            (derived_peaks if derived_peaks else "no active fields"),
            "• **Radar:** IMD urban radar page is UNREACHABLE. Lightning watch",
            "  applies blindly based on model data arrays alone.",
            "",
            "📡 **PIPELINE INTEGRITY & OUTAGES**",
            "• **Telemetry Alert:** `[CRITICAL TELEMETRY DEFICIT — ALL DISTRICT FEEDS OFFLINE]`",
            "• **System State:** Treating all alert assets as unverified. No \"nominal",
            "  green-signaling\" applied.",
            "• **Media Attached:** `state_synoptic_brief.png` [Stale/Cached Panels]",
            "",
        ]
        return "\n".join(outage_lines)

    # ── 1. Dominant Seasonal Threat Profile ─────────────────────────
    dominant_season = "RAIN"
    header_emoji = "⚡"
    subject_line = "LIGHT THUNDERSTORM WATCH"
    action_prefix = "Isolated afternoon thundershowers"
    action_items = []

    for city, data in matrix_data.items():
        tmax = float(data.get("max_temp_c", 30.0) or 30.0)
        tmin = float(data.get("min_temp_c", 20.0) or 20.0)
        vis = float(data.get("visibility_meters", 10000) or 10000)
        active_warnings = str(data.get("active_warnings") or "")

        # Summer thermal ridge check (highest priority — extreme heat)
        if tmax >= CTL_SUMMER_MAX_T or (tmax >= CTL_SUMMER_ACTIVE_T and "Thermal" in active_warnings):
            dominant_season = "SUMMER"
            header_emoji = "🔥"
            subject_line = "CRITICAL HEAT WAVE ALERT"
            action_prefix = "Critical heatwave threshold breached — immediate action required"
            action_items = [
                "Mandatory cessation of open-air heavy manual operations between 12:00 and 15:30 IST",
                "Hydration checkpoints active for all field crews",
                "Increase field team rotation frequency to every 45 minutes",
                "Provide electrolyte replacement at all hydration points",
            ]
            break
        # Winter cold wave / dense fog check (second priority)
        elif tmin <= CTL_WINTER_MIN_T or vis < CTL_WINTER_FOG_VIS:
            dominant_season = "WINTER"
            header_emoji = "❄️"
            subject_line = "SEVERE COLD WAVE & FOG WATCH"
            action_prefix = "Dangerous wind chill factor for early shift workers"
            action_items = [
                "Delay morning outdoor maintenance tracks to midday",
                "Supply thermal gear to all field crews",
                "Increase wind-chill monitoring at exposed work sites",
                "Issue visibility warnings for low-lying fog corridors",
            ]
            break

    # ── 2. Dynamic Asset & Timing Categorization ─────────────────────
    active_hazard_assets = []
    coverage_gap_assets = []
    nominal_assets = []

    # Step A: Coverage gaps first (never fabricate a station)
    for city, data in matrix_data.items():
        is_mon = data.get("is_monitored")
        if is_mon is not True or "Telemetry Deficit" in str(data.get("integrity_note", "")):
            coverage_gap_assets.append(city)
            continue

    # Collect all active rain assets BEFORE building strings, so we can
    # handle the multi-peak case (multiple timestamps per district) and the
    # title-explosion case (>6 assets → name-only in summary).
    rain_peak_times = {}  # city -> list of sorted peak times (IST)
    for city, data in matrix_data.items():
        is_mon = data.get("is_monitored")
        if is_mon is not True or "Telemetry Deficit" in str(data.get("integrity_note", "")):
            continue
        # RAIN/Convective Fallback Tracking Layer
        if data.get("corrected_rain", 0.0) > 0.0 or data.get("peak_burst", 0.0) > 0.0:
            peak_times = data.get("peak_time_ist") or []
            if not isinstance(peak_times, list):
                peak_times = [peak_times]
            # Sort and keep only distinct times
            sorted_times = sorted({str(t).strip() for t in peak_times if str(t).strip()})
            if sorted_times:
                rain_peak_times[city] = sorted_times

    # Build active_hazard_assets with proper multi-peak formatting
    for city, times in rain_peak_times.items():
        if len(times) == 1:
            active_hazard_assets.append(f"{city} (Peak: {times[0]})")
        else:
            # Compound window: e.g., "Mumbai (Peaks: 15:00 & 23:30 IST)"
            time_str = " & ".join(times)
            active_hazard_assets.append(f"{city} (Peaks: {time_str})")

    # Build active hazard assets for summer/winter seasons from the sorted
    # city list (deterministic order)
    for city, data in matrix_data.items():
        if data.get("is_monitored") is False or "Telemetry Deficit" in str(data.get("integrity_note", "")):
            continue
        if dominant_season == "SUMMER":
            tmax = float(data.get("max_temp_c", 30.0) or 30.0)
            if tmax >= CTL_SUMMER_ACTIVE_T:
                active_hazard_assets.append(f"{city} (Max: {tmax:.1f}°C)")
            else:
                nominal_assets.append(city)
        elif dominant_season == "WINTER":
            tmin = float(data.get("min_temp_c", 20.0) or 20.0)
            vis = float(data.get("visibility_meters", 10000) or 10000)
            if tmin <= CTL_WINTER_MIN_T or vis < CTL_WINTER_FOG_VIS:
                reason = f"Cold: {tmin:.1f}°C" if tmin <= CTL_WINTER_MIN_T else f"Fog: <{vis:.0f}m"
                active_hazard_assets.append(f"{city} ({reason})")
            else:
                nominal_assets.append(city)
        else:  # RAIN/Convective Fallback Tracking Layer
            # All monitored districts with no active rain/thermal/visibility
            # are nominal (do not contain peak data, so they go to nominal)
            if data.get("corrected_rain", 0.0) == 0.0 and data.get("peak_burst", 0.0) == 0.0:
                nominal_assets.append(city)
            # Districts with corrected_rain or peak_burst > 0 were already
            # added to active_hazard_assets via rain_peak_times above

    # Fix 1: Multi-asset title explosion guard.
    # If active_hazard_assets exceeds 6 items, collapse to name-only in the
    # summary line; individual peak times move to the DISTRICT BREAKDOWN
    # section below to safeguard the Telegram API character limit.
    SUMMARY_NAME_ONLY_THRESHOLD = 6
    if len(active_hazard_assets) > SUMMARY_NAME_ONLY_THRESHOLD:
        # Drop peak times from the summary line entirely
        active_str = ", ".join(city.split(" (Peak")[0] for city in active_hazard_assets)
    else:
        active_str = ", ".join(active_hazard_assets) if active_hazard_assets else "None"

    gap_str = ", ".join(coverage_gap_assets) if coverage_gap_assets else "None"
    nominal_str = ", ".join(nominal_assets) if nominal_assets else "None"

    # ── 3. Dynamic Radar Text Assembly ───────────────────────────────
    radar_checked = radar_status.get("checked", False)
    radar_reachable = radar_status.get("ok", False)
    radar_text = (
        "Verified *LIVE & REACHABLE*."
        if (radar_checked and radar_reachable)
        else "⚠️ *FEED DEGRADED / UNREACHABLE*."
    )

    # ── 4. Build the detailed district cards dynamically ─────────────
    # Fix 3: Move away from hardcoded district headers. Use a clean,
    # dynamic generator loop that only creates detailed cards for assets
    # that actually hold an active alert status during that cycle run.
    district_cards = []
    for city, data in matrix_data.items():
        # Only include districts with active rain alerts OR thermal/visibility
        # alerts (winter). Skip nominal districts to avoid empty blocks.
        is_mon = data.get("is_monitored")
        if is_mon is not True or "Telemetry Deficit" in str(data.get("integrity_note", "")):
            continue
        if dominant_season == "SUMMER":
            tmax = float(data.get("max_temp_c", 30.0) or 30.0)
            if tmax < CTL_SUMMER_ACTIVE_T:
                continue
        elif dominant_season == "WINTER":
            tmin = float(data.get("min_temp_c", 20.0) or 20.0)
            vis = float(data.get("visibility_meters", 10000) or 10000)
            if not (tmin <= CTL_WINTER_MIN_T or vis < CTL_WINTER_FOG_VIS):
                continue
        else:  # RAIN
            # Check if this district has a rain peak (possibly multi-peak)
            peak_times = rain_peak_times.get(city)
            if not peak_times:
                # Check for corrected_rain > 0 or peak_burst > 0 without peak_time
                if not (data.get("corrected_rain", 0.0) > 0.0 or data.get("peak_burst", 0.0) > 0.0):
                    continue
            # Add the card for active assets
        # Build the card
        rai = data.get("peak_burst", 0.0)
        peak_list = rain_peak_times.get(city, [])
        if peak_list:
            if len(peak_list) == 1:
                peak_display = f"Peak: {peak_list[0]}"
            else:
                time_str = " & ".join(peak_list)
                peak_display = f"Peaks: {time_str}"
            card = (
                f"⛈️ *{city} — WATCH DEVELOPING SHOWERS*\n"
                f"• *Timing & Intensity:* {peak_display}. Light intensity tracking at *{rai} mm/h*.\n"
            )
        else:
            # Fall back to Ratnagiri's peak time (standalone rain asset)
            ratnagiri = matrix_data.get("Ratnagiri") or {}
            r_time = ratnagiri.get("peak_time_ist", "16:00")
            if not str(r_time).endswith("IST"):
                r_time += " IST"
            card = (
                f"⛈️ *{city} — WATCH DEVELOPING SHOWERS*\n"
                f"• *Timing & Intensity:* Peak convective cells expected at *{r_time}*. Light intensity tracking at *{rai} mm/h*.\n"
            )
        ward = data.get("wind_speed_10m", 7)
        wdir = data.get("wind_desc_10m", "S – Onshore")
        card += f"• *Ground Wind:* {ward} km/h {wdir} Flow (dynamically sourced from current run matrix).\n"
        card += f"• *Live Radar Status:* {radar_text} Local clouds are active on the Mumbai-Konkan sweep; structural lightning watch applies where cloud cores hit.\n"
        district_cards.append(card)

    # If no district cards were produced (e.g., all nominal), fall back to
    # the Ratnagiri card for consistency (matching the template).
    if not district_cards:
        ratnagiri = matrix_data.get("Ratnagiri") or {}
        r_peak = ratnagiri.get("peak_burst", 0.0)
        r_time = ratnagiri.get("peak_time_ist", "16:00")
        r_wind_spd = ratnagiri.get("wind_speed_10m", 7)
        r_wind_dir = ratnagiri.get("wind_desc_10m", "S – Onshore")
        if not str(r_time).endswith("IST"):
            r_time += " IST"
        district_cards.append(
            f"⛈️ *Ratnagiri — WATCH DEVELOPING SHOWERS*\n"
            f"• *Timing & Intensity:* Peak convective cells expected at *{r_time}*. Light intensity tracking at *{r_peak} mm/h*.\n"
            f"• *Ground Wind:* {r_wind_spd} km/h {r_wind_dir} Flow (dynamically sourced from current run matrix).\n"
            f"• *Live Radar Status:* {radar_text} Local clouds are active on the Mumbai-Konkan sweep; structural lightning watch applies where cloud cores hit.\n"
        )

    district_cards_block = "\n\n".join(district_cards)

    # ── 5. Assemble the adaptive dispatch payload ────────────────────
    # Seasonal action items, if any
    action_lines = []
    if action_items:
        action_lines.append("• *Action Items:*")
        for i, item in enumerate(action_items, 1):
            action_lines.append(f"    {i}. {item}")

    payload = (
        f"🚨 *MAHARASHTMA WEATHER BRIEF — {header_emoji} {subject_line} 🚨\n"
        f"📅 *Validity:* {run_metrics.get('validity_date')}  |  *Run:* {run_metrics.get('run_timestamp')}\n"
        f"=========================================\n\n"
        f"❡ *SUMMARY: {subject_line}*\n"
        f"• *Active Hazard Watch:* {active_str} ({action_prefix})\n"
        f"• *Data Sensor Gaps:* {gap_str} (Alert active, local data limited)\n"
        f"• *All Clear (Normal):* {nominal_str}\n\n"
        f"=========================================\n\n"
        f"📍 *DISTRICT BREAKDOWN & OPERATIONAL DETAILS*\n\n"
        f"{district_cards_block}\n"
        f"🌀 *REGIONAL FORECAST & GLOBAL WINDS*\n"
        f"• *Cyclone Trackers:* {synoptic_context.get('cyclone_status', 'Nominal. Zero closed systems.')}\n"
        f"• *Winter Transition:* {synoptic_context.get('winter_transition_status', 'Monsoon currents deactivated.')}\n"
        f"• *El Niño Index:* {synoptic_context.get('el_nino_status', 'System feed unavailable this cycle; broader global oceanic tracking phase cannot be verified.')}\n\n"
        f"=========================================\n"
    )

    # Append seasonal action items if any
    if action_lines:
        payload += "\n".join(action_lines) + "\n\n"

    payload += (
        f"⚙️ *System Run Profile: RC={run_metrics.get('rc', 0)} "
        f"| Output Size: __TEXT_LEN__ Chars | Attachments: "
        f"4-Panel Weather Chart (state_synoptic_brief.png) + "
        f"12-Frame Animation Loop (mmr_asset_brief.mp4)*"
    )

    # Calculate exact text footprint for the placeholder line dynamically
    text_len_estimate = len(payload) - len("__TEXT_LEN__") + 4
    final_payload = payload.replace("__TEXT_LEN__", str(text_len_estimate))

    return final_payload


def build_one_glance_dispatch(matrix_data, radar_status, synoptic_context, run_metrics) -> str:
    """
    Renders the simplified deep-detail hybrid weather brief dispatch payload
    via the adaptive seasonal engine. Calls build_adaptive_one_glance_dispatch()
    and returns the finalized payload.

    matrix_data: {district: {is_monitored, integrity_note, corrected_rain,
                              peak_burst, peak_time_ist, wind_speed_10m,
                              wind_desc_10m, raw_rain, max_temp_c,
                              min_temp_c, visibility_meters}}
    radar_status: {"checked": bool, "ok": bool}
    synoptic_context: {"cyclone_status", "winter_transition_status",
                       "el_nino_status"}
    run_metrics: {"validity_date", "run_timestamp", "rc"}
    """
    # Primary: adaptive seasonal engine (handles rain / summer / winter)
    return build_adaptive_one_glance_dispatch(
        matrix_data, radar_status, synoptic_context, run_metrics)
