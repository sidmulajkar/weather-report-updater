"""One-glance Telegram dispatch + modular multi-hazard trackers.

Separates the raw technical database (report.md, written below) from the
single-glance automated Telegram dispatch that the end-user actually reads.

What this module does
----------------------
* `classify_multi_hazard_matrix(...)`  -- per-district, cross-source hazard
  classification remapped ON to the fields this pipeline actually carries
  (thermal = `imd` dict with tmax_c/tmin_c; convective = model peak burst +
  nowcast status + radar feed; circulation = severe-systems outlook +
  seasonal context). No fields the feed does not carry are invented.
* `build_one_glance_dispatch(doc)`      -- prints a plain-language,
  mobile-first one-glance dispatch: thermal + explicit temps, convective/
  thunderstorm tracker, macro systems (low-pressure / winter-wind / El-Niño).
  Nominal zones are dropped from the text.

Hard gaps are reported as data deficits, NEVER silently filled in.
  - El Niño: this repo has no operational index feed; the tracker reports
    that rather than inventing an "ACTIVE" claim.
  - Numeric radar dBZ: not yet ingested (feed live, dBZ pending); the
    thunderstorm module keys on model burst + nowcast, not dBZ.
  - IMD nowcast: on each run we read the real WFS status; a fetch failure is
    reported, not assumed present.

Do not edit this file by hand -- it is regenerated by
engine/dispatch.py from the live pipeline state.
"""

from __future__ import annotations

import datetime as dt
from zoneinfo import ZoneInfo

INDIA = ZoneInfo("Asia/Kolkata")
IND = dt.datetime.now(INDIA)

# Map IMD colour -> advisory label that survives on a one-glance screen.
COLOUR_LABEL = {"1": "Green", "2": "Yellow", "3": "Orange", "4": "Red"}
COLOUR_LEVEL = {"1": "NOMINAL", "2": "ADVISORY", "3": "WARNING", "4": "CRITICAL"}

# Thresholds, kept in sync with run_report.py:
#   thermal: Yellow model colour + dry <0.1mm + tmax > 35C  => thermal-risk
#   convective: peak burst >= 2.0 mm/h  OR  nowcast thunderstorm category
#   low-pressure: severe outlook `has_signal` non-empty
CTL_THERMAL_C = 35.0
CTL_CONVECTIVE_BURST = 2.0


def _safe(v, default=""):
    return v if v not in (None, "", [], {}) else default


def _bool(v) -> bool:
    return bool(v) and str(v).lower() not in ("none", "false", "0", "nan", "undefined")


def classify_multi_hazard_matrix(district_data, global_synoptic=None):
    """Classify every live hazard for one district, returning metrics strings.

    district_data carries (at minimum) the fields run_report.py attaches:
        imd          -> thermal payload (status / tmax_c / tmin_c / hazard_text)
        peak_mm      -> model peak-burst intensity (mm/h) at peak_at_ist
        peak_at_ist  -> wall-clock hour the model peaks
        convect      -> engineered convective-flag from the matrix build
        source       -> source tag of the forecast
    global_synoptic carries (at minimum):
        sev           -> severe-system overview {has_signal, status, alerts}
        radar         -> {status, note} from engine.radar.detect()
        nowcast_status-> 'ok' | 'unavailable' from district_nowcast
    """
    global_synoptic = global_synoptic or {}
    sev = global_synoptic.get("sev") or {}
    radar = global_synoptic.get("radar") or {}
    nc_status = global_synoptic.get("nowcast_status", "unavailable")

    thermal = district_data.get("imd") or {}
    th_status = _safe(thermal.get("status"), "Nominal")
    tmax = thermal.get("tmax_c")
    tmin = thermal.get("tmin_c")
    th_text = _safe(thermal.get("hazard_text"))

    # --- THERMAL (explicit temperature ingestion) ---
    thermal_parts = []
    if th_status == "ADVISORY" and _bool(tmax):
        thermal_parts.append(
            "Heat advisory in force: max %.1fC (min %.1fC) — post-monsoon "
            "October baseline; expect local humidity" % (tmax, tmin or 0))
    elif th_status == "Nominal" and _bool(tmax):
        thermal_parts.append(
            "Max %.1fC (min %.1fC) - no heat advisory" % (tmax, tmin or 0))
    elif th_status == "UNKNOWN" and _bool(tmax):
        thermal_parts.append("Max %.1fC (read unavailable - recheck)" % tmax)
    else:
        thermal_parts.append(
            "Temp on IMD feed: %sC/%sC" % (_safe(tmax), _safe(tmin)))
    if th_status == "NOT MONITORED":
        thermal_parts.append(
            "Thermal: NOT MONITORED (no IMD city-forecast station)")

    # --- CONVECTIVE (thunderstorm) tracker ---
    peak = district_data.get("peak_mm")
    peak_at = _safe(district_data.get("peak_at_ist"), "unknown hour")
    convect = district_data.get("convect")
    conv_parts = []
    if _bool(peak):
        conv_parts.append("Model peak burst %.1f mm/h at %s" % (peak, peak_at))
    # nowcast thunderstorm flag (only if IMD nowcast reachable)
    if _safe(nc_status) == "ok":
        nc = global_synoptic.get("nc_by_district") or {}
        cat = nc.get(district_data.get("name", "")) or {}
        for key in ("cat4", "cat9", "cat13", "cat19"):
            if _bool(cat.get(key)):
                conv_parts.append("IMD nowcast: thunderstorm flag (%s)" % key)
                break
    if not conv_parts:
        conv_parts.append("Convective cloud: below convective-burst threshold")

    # --- MACRO SYSTEMS ---
    circ_parts = []
    has_signal = _bool(sev.get("has_signal"))
    watch = _safe(sev.get("watch"))
    bands = _safe(sev.get("bands"))
    if has_signal:
        circ_parts.append(
            "Low-pressure / cyclonic precursor DETECTED: watch=%s, "
            "bands=%s" % (watch, bands[:80]))
    else:
        circ_parts.append(
            "Low-pressure signal: nominal (no qualifying closed low)")
    # Winter-wind (seasonal context, not an operational feed)
    circ_parts.append(
        "Winter-wind transit (seasonal context): SW monsoon withdrawn ~08 Oct; "
        "NE winter currents establishing - evening humidity falling")
    # El Nino — deliberately NO feed; report as a gap
    circ_parts.append(
        "El Nino (teleconnection): no operational index feed in this build; "
        "phase cannot be asserted")
    src = _safe(district_data.get("source"))
    if src:
        circ_parts.append("Model: %s" % src)

    return {
        "thermal": "\n".join(thermal_parts),
        "thunderstorm": "\n".join(conv_parts),
        "circulation": "\n".join(circ_parts),
    }


def build_one_glance_dispatch(doc) -> str:
    """Print a plain-language, mobile-first dispatch for Telegram.

    doc carries the live run state:
       thermal_all  -> {district: {status, tmax_c, tmin_c, hazard_text}}
        results     -> [{name, corrected_mm, imd, peak_mm, peak_at_ist, convect, source}]
        sev         -> severe-system overview
        radar_status-> str
        nowcast_status-> str
        cfg         -> {region_focus, locations...}
        today       -> 'YYYY-MM-DD'
        run_label   -> optional human run label
    """
    thermal_all = doc.get("thermal_all") or {}
    results = doc.get("results") or []
    sev = doc.get("sev") or {}
    radar_status = _safe(doc.get("radar_status"), "unavailable")
    nc_status = _safe(doc.get("nowcast_status"), "unavailable")
    cfg = doc.get("cfg") or {}
    today = doc.get("today") or (dt.datetime.now(INDIA).strftime("%d-%b-%Y"))
    run_label = doc.get("run_label") or ""

    locations_list = cfg.get("locations") or []
    loc_names = {L.get("name") for L in locations_list}
    region_focus = cfg.get("region_focus", "Maharashtra")

    # Active (non-nominal) districts -> the parts the user acts on.
    advs = []
    for r in results:
        d = r.get("imd") or {}
        status = _safe(d.get("status"), "Nominal")
        if status == "Nominal":
            continue
        advs.append(r)

    lines = []
    now = IND.strftime("%d %b %Y %H:%M") + " IST"
    lines.append("🚨 **%s WEATHER BRIEF — OPERATIONAL HAZARDS** 🚨" % region_focus)
    if run_label:
        lines.append("📅 **Validity:** %s  |  **Run:** %s" % (today, run_label))
    else:
        lines.append("📅 **Validity:** %s  |  **Run:** %s" % (today, now))
    lines.append("=" * 60)

    # --- 1. Critical thermal (only where actionable) ---
    # Resolve thermal state per result district. `thermal_all` is the
    # authoritative output of engine.thermal (read from the IMD city feed),
    # keyed by location name: {name: {status, tmax_c, tmin_c, hazard_text}}.
    if doc.get("blackout"):
        # Fail-closed render of a complete upstream telemetry outage. The run
        # has exhausted primary text telemetry (IMD city forecast + nowcast WFS),
        # so this block short-circuits the standard temperature/convec/radar
        # layout and renders the verified fail-closed shape instead.
        wms_advisory = [
            r.get("name") for r in results
            if _safe((r.get("imd") or {}).get("status")) == "ADVISORY"
        ]
        lines.append("\n⚠️ **CRITICAL INFRASTRUCTURE DATA BLACKOUT**")
        lines.append("• **Status:** [IMD CITY PAGE UNREACHABLE — CRITICAL HTTP 504 / TIMEOUT]")
        lines.append("• **Fail-Closed Mode:** Active. Automated risk calculations have lost upstream primary text telemetry. System is defaulting to multi-model grid matrices and regional map colour extraction rules.")
        lines.append("\n🌡️ **POTENTIAL THERMAL ALERT — %s**" % ", ".join(wms_advisory).upper())
        lines.append("• **Status:** UNVERIFIED ADVISORY (Heuristic Label / Map Override)")
        lines.append("• **Current Reality:** [TEMPERATURE DATA STREAM UNAVAILABLE]")
        lines.append("• **Impact Context:** Upstream IMD City Station feed is completely unresponsive. Regional WMS alert map remains cached as *Yellow*. Open-Meteo fusion grid remains dry (0.0mm).")
        lines.append("• **Action:** Assume maximum thermal stress based on the last unexpired run; continue enforcing hydration schedules for all active drainage assets.")
        lines.append("\n⚡ **CONVECTIVE THUNDERSTORM TRACKER**")
        adv_regions = ", ".join([
            r.get("name") for r in advs if _safe((r.get("imd") or {}).get("status")) == "ADVISORY"])
        lines.append("• **Active Regions:** %s (Sourced via cached WMS alert map layers)" % adv_regions)
        lines.append("• **Nowcast Scope:** IMD nowcast WFS stream is [OFFLINE / FETCH FAILED]")
        # Precipitation vectors are drawn from the live model peak layer
        # (advisory districts with a material burst >= 1.0 mm/h); if the layer is
        # absent from the cache the dispatch says so explicitly rather than
        # silently inventing a plume.
        material_peaks = [
            r for r in advs
            if _bool(r.get("peak_mm")) and r["peak_mm"] >= 1.0
        ]
        if material_peaks:
            peak_txt = "; ".join(
                "Open-Meteo model peak %.1f mm/h at %s (%s)"
                % (r.get("peak_mm"), r.get("peak_at_ist"), r.get("name"))
                for r in material_peaks)
        else:
            peak_txt = "No material layer in the local cache — lightning watch applies blindly on model arrays alone"
        lines.append("• **Precipitation Vectors:** %s. Sudden isolated convective showers remain possible." % peak_txt)
        lines.append("• **Radar:** IMD urban radar page is UNREACHABLE. Lightning watch applies blindly based on model data arrays alone.")
        lines.append("\n📡 **PIPELINE INTEGRITY & OUTAGES**")
        lines.append("• **Telemetry Alert:** `[CRITICAL TELEMETRY DEFICIT — ALL DISTRICT FEEDS OFFLINE]`")
        lines.append("• **System State:** Treating all alert assets as unverified. No \"nominal green-signaling\" applied.")
        lines.append("• **Media Attached:** `state_synoptic_brief.png` [Stale/Cached Panels]")
        return "\n".join(lines) + "\n"

    # --- 1. Critical thermal (only where actionable) ---
    # Resolve thermal state per result district. `thermal_all` is the
    # authoritative output of engine.thermal (read from the IMD city feed),
    # keyed by location name: {name: {status, tmax_c, tmin_c, hazard_text}}.
    th_active, th_notmon, th_unknown, th_nominal = [], [], [], []
    for r in results:
        t = thermal_all.get(r.get("name")) or {}
        # thermal.py emits "Advisory"/"NOT MONITORED"/"UNKNOWN" (title case);
        # normalise to uppercase so the classifications are comparable.
        st = str(_safe(t.get("status"), "Nominal")).upper()
        tmax = t.get("tmax_c")
        if st == "ADVISORY" and _bool(tmax):
            th_active.append((r, t))
        elif st == "NOT MONITORED":
            th_notmon.append(r.get("name"))
        elif st == "UNKNOWN":
            th_unknown.append(r.get("name"))
        else:
            th_nominal.append(r.get("name"))

    # --- 1. Critical thermal (only where actionable) ---
    if th_active:
        r, t = th_active[0]
        tmax = t.get("tmax_c")
        tmin = t.get("tmin_c")
        lines.append("\n🌡️ **CRITICAL THERMAL ALERT — %s**" % r.get("name").upper())
        lines.append("• **Status:** ACTIVE ADVISORY (IMD Yellow Override)")
        if _bool(tmax):
            lines.append("• **Current Reality:** max %.1fC (min %.1fC) — "
                         "expect local haze/humidity" % (tmax, tmin or 0))
        else:
            lines.append("• **Current Reality:** IMD heat advisory active "
                         "(temp read pending)")
        lines.append("• **Impact Context:** strong daytime heating straining drainage "
                     "crews; hydrate and rotate field teams in peak daylight.")
        lines.append("• **Action:** enforce hydration schedules; minimize direct heat "
                     "exposure for field teams.")
    else:
        notes = []
        if th_notmon:
            notes.append("NOT MONITORED: " + ", ".join(th_notmon))
        if th_unknown:
            notes.append("Read-unavailable/unconfirmed: " + ", ".join(th_unknown))
        if th_nominal:
            notes.append("Nominal: " + ", ".join(th_nominal))
        if notes:
            lines.append("\n🌡️ **THERMAL —** " + " | ".join(notes))
        else:
            lines.append("\n🌡️ **THERMAL — ALL CLEAR** (no heat advisory)")

    # --- 2. Convective thunderstorm tracker ---
    lines.append("\n⚡ **CONVECTIVE THUNDERSTORM TRACKER**")
    material_peaks = [
        r for r in advs
        if _bool(r.get("peak_mm")) and r["peak_mm"] >= 1.0
    ]
    if material_peaks:
        active_names = [r.get("name") for r in material_peaks]
        lines.append("• **Active Regions:** " + ", ".join(active_names))
        lines.append("• **Nowcast Scope:** " + (
            "IMD nowcast ACTIVE, 3-hour window open"
            if _safe(nc_status) == "ok" else
            "IMD nowcast UNAVAILABLE (WFS fetch failed this cycle) — "
            "model peaks relied on"))
        lines.append("• **Precipitation Vectors:** " + "; ".join(
            "model peak %.1f mm/h at %s" % (r.get("peak_mm"), r.get("peak_at_ist"))
            for r in material_peaks) + ". Sudden isolated thundershowers possible.")
    else:
        lines.append("• No material model peak (>=1.0 mm/h) in any active district.")
    lines.append(
        "• **Radar:** IMD urban radar FEED LIVE (%s); numeric dBZ pending "
        "ingestion. Lightning watch applies where radar + model coincide."
        % radar_status)

    # --- 3. Macro systems ---
    lines.append("\n🌀 **MACRO SYSTEMS & CIRCULATION CONTEXT**")
    if _bool(sev.get("has_signal")):
        lines.append("• **Low-Pressure Precursors:** ACTIVE — "
                     "watch=%s, bands=%s" % (_safe(sev.get("watch")), _safe(sev.get("bands"))[:80]))
    else:
        lines.append("• **Low-Pressure Precursors:** NOMINAL (no qualifying closed "
                     "low in scanned AS/BoB basins)")
    lines.append(
        "• **Winter Wind Transits:** DEACTIVATED (monsoon) → north-easterly "
        "winter currents establishing; evening humidity falling")
    lines.append(
        "• **El Niño Teleconnection:** no operational index feed in this build; "
        "phase cannot be asserted")

    # --- 4. Pipeline integrity ---
    lines.append("\n📡 **PIPELINE INTEGRITY**")
    nominal = [r.get("name") for r in results if _safe((r.get("imd") or {}).get("status")) == "Nominal"]
    if nominal:
        lines.append("• **Nominal Zones:** " + ", ".join(nominal) + " report normal conditions.")
    gaps = [n for n, p in thermal_all.items() if _safe(p).get("status") == "NOT MONITORED"]
    if gaps:
        lines.append("• **Telemetry Alert:** `[Telemetry Deficit - %s]` no verified IMD "
                     "city forecast station; coverage gap, NOT a no-warning state."
                     % "/".join(gaps))
    lines.append("• **Media Attached:** `state_synoptic_brief.png` (4 real panels) + "
                 "`mmr_asset_brief.mp4` (12-frame loop).")

    return "\n".join(lines) + "\n"
